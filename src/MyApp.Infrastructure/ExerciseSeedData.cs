    public static async Task SeedAsync(DbContext db, ILogger logger, CancellationToken ct = default)
    {
        logger.LogInformation("Засівання каталогу базових вправ...");

        var set = db.Set<Exercise>();
        var existing = await set.IgnoreQueryFilters().ToListAsync(ct);

        foreach (var seed in Seeds)
        {
            var exercise = existing.Find(e => e.Name == seed.Name);

            if (exercise is null)
            {
                set.Add(new Exercise
                {
                    Name = seed.Name,
                    EquipmentType = seed.Equipment,
                    Description = seed.Description,
                    Technique = seed.Technique,
                });
            }
            else if (exercise.Technique is null)
            {
                exercise.EquipmentType = seed.Equipment;
                exercise.Description ??= seed.Description;
                exercise.Technique = seed.Technique;
                exercise.UpdatedAt = DateTimeOffset.UtcNow;
            }
        }

        await db.SaveChangesAsync(ct);
    }
